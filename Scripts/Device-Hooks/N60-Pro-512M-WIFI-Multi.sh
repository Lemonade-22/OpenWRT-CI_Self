#!/bin/bash
# Netcore N60 Pro 512M —— WIFI-Multi。
#
# 多 SSID 不靠改固件：分区与产物逻辑跟 WIFI-YES/NO 完全一样，直接转给
# N60-Pro-512M-WIFI-NO.sh。这里额外做三件事：
#   1. 把 Custom/multiwifi/files 并进 files/
#   2. 按 workflow 的 SSID/密码重写 multiwifi.conf
set -euo pipefail
ci_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

case "${WRT_CONFIG:-}" in
	N60-Pro-512M-WIFI-Multi) ;;
	*)
		echo "::error::N60 Pro multiwifi hook invoked for the wrong configuration" >&2
		exit 2
		;;
esac

case "${1:-}" in
	configure)
		src="$ci_root/Custom/multiwifi/files"
		[ -d "$src" ] || {
			echo "::error::missing $src" >&2; exit 1; }

		mkdir -p ./files
		cp -a "$src"/. ./files/

		# 副 SSID 的前缀和密码跟着 workflow 走，跟主 SSID 保持一致
		prefix="${WRT_SSID:-WiFi}"
		key="${WRT_WORD:-12345678}"
		prefix="${prefix//\"/}"
		key="${key//\"/}"
		conf="./files/etc/multiwifi.conf"
		{
			printf "# generated by Device-Hooks/N60-Pro-512M-WIFI-Multi.sh\n"
			printf "COUNT=30\n"
			printf "PREFIX=%s\n" "$prefix"
			printf "KEY=%s\n" "$key"
			printf "BASE=188.181\n"
			printf "ISOLATE=1\n"
		} > "$conf"

		grep -qx "COUNT=30" "$conf" || {
			echo "::error::failed to stage $conf" >&2; exit 1; }
		echo "N60 Pro: multiwifi files staged (prefix=$prefix)"
		;;
esac

exec bash "$(dirname "$0")/N60-Pro-512M-WIFI-NO.sh" "$@"